export function findStop(id: string) {
  for (const season of seasons) {
    const stop = season.stops.find((item) => item.id === id)
    if (stop) return { season, stop }
  }
  return null
}

export function featuredChoice(stop: Season["stops"][number]) {
  return stop.choices.find((choice) => choice.fits) ?? stop.choices[0]
}

export function weekSeasonId(date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 1)
  const diff = Math.floor((date.getTime() - start.getTime()) / 86_400_000)
  const week = Math.floor((diff + start.getDay()) / 7)
  return seasons[Math.abs(week) % seasons.length].id
}
